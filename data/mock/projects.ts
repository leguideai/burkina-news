export const getProjectBySlug = (slug: string): Project | undefined =>
  projects.find(p => p.slug === slug)

export const getProjectsByCategory = (code: string): Project[] =>
  projects.filter(p => p.category === code)

export const getProjectsByStatus = (status: string): Project[] =>
  projects.filter(p => p.currentStatus === status)

export const getProjectStats = () => {
  const total = projects.length
  const byStatus = projects.reduce((acc, p) => {
    acc[p.currentStatus] = (acc[p.currentStatus] || 0) + 1
    return acc
  }, {} as Record<string, number>)
  return { total, byStatus }
}
